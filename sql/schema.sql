-- Personal Budgeting, Expense Tracking & Tagging System
-- Run this whole file in MySQL Workbench (MySQL 8.0.16+ for CHECK constraints)

CREATE DATABASE IF NOT EXISTS budget_db;
USE budget_db;

CREATE TABLE user_account (
    user_id INT PRIMARY KEY AUTO_INCREMENT,
    name VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,          -- added for login (bcrypt hash)
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE account (
    account_id INT PRIMARY KEY AUTO_INCREMENT,
    user_id INT NOT NULL,
    account_name VARCHAR(50) NOT NULL,
    account_type VARCHAR(20) NOT NULL,
    opening_balance DECIMAL(10,2) DEFAULT 0,
    FOREIGN KEY (user_id) REFERENCES user_account(user_id),
    CHECK (account_type IN ('Cash', 'Bank', 'Card'))
);

CREATE TABLE tag (
    tag_id INT PRIMARY KEY AUTO_INCREMENT,
    user_id INT NOT NULL,
    tag_name VARCHAR(30) NOT NULL,
    FOREIGN KEY (user_id) REFERENCES user_account(user_id),
    UNIQUE (user_id, tag_name)
);

CREATE TABLE category (
    category_id INT PRIMARY KEY AUTO_INCREMENT,
    user_id INT NOT NULL,
    parent_category_id INT NULL,
    category_name VARCHAR(50) NOT NULL,
    category_type VARCHAR(20) NOT NULL,
    FOREIGN KEY (user_id) REFERENCES user_account(user_id),
    FOREIGN KEY (parent_category_id) REFERENCES category(category_id),
    CHECK (category_type IN ('Income', 'Expense'))
);

CREATE TABLE budget (
    budget_id INT PRIMARY KEY AUTO_INCREMENT,
    user_id INT NOT NULL,
    budget_name VARCHAR(50) NOT NULL,
    limit_amount DECIMAL(10,2) NOT NULL,          -- added: the spending limit
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    FOREIGN KEY (user_id) REFERENCES user_account(user_id),
    CHECK (period_end >= period_start),
    CHECK (limit_amount > 0)
);

CREATE TABLE budget_category (
    budget_id INT,
    category_id INT,
    PRIMARY KEY (budget_id, category_id),
    FOREIGN KEY (budget_id) REFERENCES budget(budget_id) ON DELETE CASCADE,
    FOREIGN KEY (category_id) REFERENCES category(category_id)
);

CREATE TABLE recurring_template (
    template_id INT PRIMARY KEY AUTO_INCREMENT,
    user_id INT NOT NULL,
    account_id INT NOT NULL,
    category_id INT NOT NULL,
    transaction_type VARCHAR(20) NOT NULL,
    amount DECIMAL(10,2) NOT NULL,
    frequency VARCHAR(20) NOT NULL,
    next_run_date DATE NOT NULL,
    notes VARCHAR(200) NULL,
    FOREIGN KEY (user_id) REFERENCES user_account(user_id),
    FOREIGN KEY (account_id) REFERENCES account(account_id),
    FOREIGN KEY (category_id) REFERENCES category(category_id),
    CHECK (transaction_type IN ('Income', 'Expense')),
    CHECK (frequency IN ('Weekly', 'Monthly', 'Yearly')),
    CHECK (amount > 0)
);

CREATE TABLE `transaction` (
    transaction_id INT PRIMARY KEY AUTO_INCREMENT,
    user_id INT NOT NULL,
    account_id INT NOT NULL,
    category_id INT NOT NULL,
    tag_id INT NULL,                              -- one optional tag (no transaction_tag table)
    template_id INT NULL,                         -- set when generated by a recurring template
    transaction_type VARCHAR(20) NOT NULL,
    amount DECIMAL(10,2) NOT NULL,
    transaction_date DATE NOT NULL,
    merchant_name VARCHAR(50) NULL,
    notes VARCHAR(200) NULL,
    FOREIGN KEY (user_id) REFERENCES user_account(user_id),
    FOREIGN KEY (account_id) REFERENCES account(account_id),
    FOREIGN KEY (category_id) REFERENCES category(category_id),
    FOREIGN KEY (tag_id) REFERENCES tag(tag_id),
    FOREIGN KEY (template_id) REFERENCES recurring_template(template_id),
    CHECK (transaction_type IN ('Income', 'Expense')),
    CHECK (amount > 0)
);
